const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.BTC_LENS_URL || 'http://127.0.0.1:5081';
const screenshotDir = process.env.SCREENSHOT_DIR || 'test-results/screenshots';
const checks = [];
const pause = page => page.waitForTimeout(350);

(async () => {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : 'chromium'), headless: true });
  let page;
  const errors = [];
  try {
    page = await browser.newPage({ viewport: { width:1440, height:1000 }, locale:'zh-CN', timezoneId:'Asia/Shanghai' });
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type()==='error') errors.push(m.text()); });
    fs.mkdirSync(screenshotDir,{ recursive:true });
    await page.goto(base);
    await page.waitForSelector('.chart-host canvas');
    await page.getByRole('button',{name:'演示',exact:true}).click();
    await page.getByRole('button',{name:'新回放',exact:true}).click();
    await pause(page);
    assert.equal(await page.locator('.event-row').count(),0);
    assert.ok(await page.locator('.chart-host canvas').count() >= 3);
    await page.waitForSelector('.flow-chart canvas');
    assert.equal(Number(await page.locator('.flow-chart').getAttribute('data-cvd-points')),240);
    assert.equal(Number(await page.locator('.flow-chart').getAttribute('data-oi-samples')),120);
    assert.equal(Number(await page.locator('.flow-chart').getAttribute('data-oi-segments')),1);
    assert.match(await page.locator('[data-testid="order-flow"]').innerText(),/独立合成/);
    await page.getByLabel('订单流显示周期').selectOption('15');
    await pause(page);
    assert.equal(await page.getByLabel('订单流显示周期').inputValue(),'15');
    checks.push('offline synthetic order flow / three panes / sampling');
    assert.ok(!(await page.locator('body').innerText()).includes('v@'));
    await page.screenshot({path:path.join(screenshotDir,'radar.png'),fullPage:true});
    checks.push('chart / synthetic replay / no literal Razor tokens');

    for (const [route,file] of [['/journal','journal.png'],['/statistics','statistics.png']]) {
      await page.goto(base+route); await pause(page);
      await page.screenshot({path:path.join(screenshotDir,file),fullPage:true});
    }
    await page.goto(base); await page.waitForSelector('.chart-host canvas');
    await page.getByRole('button',{name:'推进 5 根',exact:true}).click();
    await page.waitForSelector('.event-row');
    assert.equal(await page.locator('.event-row').count(),1);
    await page.getByRole('button',{name:'推进 5 根',exact:true}).click();
    await pause(page); assert.equal(await page.locator('.event-row').count(),1);
    await page.reload(); await page.waitForSelector('.event-row');
    assert.equal(await page.locator('.event-row').count(),1);
    checks.push('first entry / deduplication / reload persistence');

    await page.locator('.event-row').first().click();
    await page.getByText('查看保存的证据数据',{exact:true}).click();
    const snapshotBefore = await page.locator('.json-block').innerText();
    assert.match(snapshotBefore,/"cutoff"/);
    await page.getByRole('link',{name:'关联交易记录 →',exact:true}).click();
    await page.waitForSelector('[aria-label="交易编辑"]');
    const entry = Number(await page.getByLabel('实际开仓价',{exact:true}).inputValue());
    await page.getByLabel('初始止损（可留空）',{exact:true}).fill(String(entry-100));
    await page.getByLabel('原定目标（可留空）',{exact:true}).fill(String(entry+300));
    await page.getByLabel('这笔交易已平仓',{exact:true}).check();
    await page.getByLabel('实际平仓价',{exact:true}).fill(String(entry+200));
    const time = await page.getByLabel('开仓时间（北京时间）',{exact:true}).inputValue();
    const later = new Date(time+'Z'); later.setUTCHours(later.getUTCHours()+1);
    await page.getByLabel('平仓时间（北京时间）',{exact:true}).fill(later.toISOString().slice(0,16));
    await page.getByLabel('总手续费（USDT）',{exact:true}).fill('0.6');
    await page.getByLabel('资金费（收入为正，USDT）',{exact:true}).fill('0');
    await page.getByLabel('复盘记录',{exact:true}).fill('Browser smoke：验证到区证据关联与平仓记录。');
    await page.getByLabel('标签（用逗号分隔）',{exact:true}).fill('浏览器验收');
    await page.locator('[aria-label="交易编辑"] input[type=file]').setInputFiles(path.join(screenshotDir,'radar.png'));
    await page.waitForSelector('.screenshot-preview img');
    await page.getByRole('button',{name:'保存交易',exact:true}).click();
    await page.waitForSelector('[aria-label="交易编辑"]',{state:'hidden'});
    await page.waitForSelector('.review-content');
    assert.equal(await page.locator('[aria-label="交易编辑"]').count(),0);
    assert.match(await page.locator('.detail-pnl').innerText(),/\+1\.40/);
    assert.match(await page.locator('.review-content').innerText(),/Browser smoke/);
    assert.equal(await page.locator('.trade-screenshot img').count(),1);
    await page.reload(); await pause(page);
    assert.match(await page.locator('.trade-table').innerText(),/\+1\.40/);
    checks.push('alert → journal / costs / R / review persistence');

    await page.getByRole('button',{name:'导入 CSV',exact:true}).click();
    const id = 'browser-'+Date.now();
    const header = 'external_id,side,entry_time,exit_time,entry_price,exit_price,quantity_btc,initial_stop,target,fees,funding,reason,review,tags';
    const csv = header+'\n'+id+',Long,2026-09-20T09:00:00+08:00,2026-09-20T10:00:00+08:00,67000,67300,0.01,66900,67300,0.6,0,CSV browser,CSV verification,浏览器导入\n';
    const upload = {name:'browser.csv',mimeType:'text/csv',buffer:Buffer.from(csv)};
    await page.locator('[aria-label="CSV 导入"] input[type=file]').setInputFiles(upload);
    await page.getByRole('button',{name:'确认导入',exact:true}).click();
    await page.waitForSelector('[aria-label="CSV 导入"]',{state:'hidden'});
    const afterFirst = await page.locator('.trade-table tbody tr').count();
    await page.getByRole('button',{name:'导入 CSV',exact:true}).click();
    await page.locator('[aria-label="CSV 导入"] input[type=file]').setInputFiles(upload);
    await page.getByRole('button',{name:'确认导入',exact:true}).click();
    await page.waitForSelector('[aria-label="CSV 导入"]',{state:'hidden'});
    assert.equal(await page.locator('.trade-table tbody tr').count(),afterFirst);
    checks.push('CSV preview / transactional import / repeated import');

    await page.goto(base); await page.waitForSelector('.chart-host canvas');
    const original = page.locator('.watch-card').filter({hasText:'回踩观察 · 演示关注区'});
    await original.getByRole('button',{name:'编辑',exact:true}).click();
    await page.getByLabel('名称',{exact:true}).fill('原关注区 · v2');
    await page.getByLabel('下边界',{exact:true}).fill('66900');
    await page.getByLabel('上边界',{exact:true}).fill('67000');
    await page.getByRole('button',{name:'保存并启用',exact:true}).click();
    await page.waitForSelector('[aria-label="关注区编辑"]',{state:'hidden'});
    assert.match(await page.locator('.watch-card').first().innerText(),/v2/);
    await page.locator('.event-row').first().click();
    await page.getByText('查看保存的证据数据',{exact:true}).click();
    assert.equal(await page.locator('.json-block').innerText(),snapshotBefore);
    await page.getByRole('button',{name:'关闭提醒',exact:true}).click();
    checks.push('watch revision / immutable original event');

    await page.locator('.lower-grid table .text-button').first().click();
    await page.getByLabel('名称',{exact:true}).fill('自动参考加入关注');
    await page.getByRole('button',{name:'保存并启用',exact:true}).click();
    await page.waitForSelector('[aria-label="关注区编辑"]',{state:'hidden'});
    assert.match(await page.locator('.watch-list').innerText(),/自动参考加入关注/);
    await page.getByRole('button',{name:'图上选区',exact:false}).click();
    await page.waitForFunction(()=>document.querySelector('.chart-host')?.style.cursor === 'crosshair');
    const box = await page.locator('.chart-host').boundingBox();
    await page.mouse.click(box.x+box.width*.4,box.y+box.height*.3);
    await page.mouse.click(box.x+box.width*.4,box.y+box.height*.55);
    await page.waitForSelector('[aria-label="关注区编辑"]');
    assert.ok(Number(await page.getByLabel('上边界',{exact:true}).inputValue()) > Number(await page.getByLabel('下边界',{exact:true}).inputValue()));
    await page.getByLabel('名称',{exact:true}).fill('图上手动选区');
    await page.getByRole('button',{name:'保存并启用',exact:true}).click();
    await page.waitForSelector('[aria-label="关注区编辑"]',{state:'hidden'});
    checks.push('auto zone promotion / chart two-click region');

    await page.getByRole('button',{name:'生成报告 ↗',exact:true}).click();
    await page.waitForSelector('[aria-label="观察报告"]');
    assert.match(await page.locator('[aria-label="观察报告"]').innerText(),/尚缺证据/);
    await page.getByRole('button',{name:'关闭报告',exact:true}).click();
    await page.locator('.timeframes').getByRole('button',{name:'4H',exact:true}).click();
    await pause(page);
    await page.locator('.timeframes').getByRole('button',{name:'5m',exact:true}).click();
    await pause(page);
    checks.push('evidence report / timeframe switching');

    await page.setViewportSize({width:390,height:844});
    await pause(page);
    assert.ok(await page.evaluate(()=>document.body.scrollWidth<=window.innerWidth));
    await page.screenshot({path:path.join(screenshotDir,'mobile.png'),fullPage:true});
    checks.push('mobile layout without page overflow');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:checks.length,checks,consoleErrors:errors,screenshots:screenshotDir},null,2));
  } catch (error) {
    console.error(JSON.stringify({completed:checks,consoleErrors:errors}));
    if(page) await page.screenshot({path:path.join(screenshotDir,'failure.png'),fullPage:true});
    throw error;
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
